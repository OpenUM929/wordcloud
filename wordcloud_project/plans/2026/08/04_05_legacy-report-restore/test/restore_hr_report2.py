import io, sys
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")

P = ("D:/dev/wordcloud/wordcloud_project/plans/2026/07/"
     "27_03_completion-report/result/인사처결과보고서_260727.md")

raw = open(P, encoding="utf-8", newline="").read()
EOL = "\r\n" if "\r\n" in raw else "\n"
txt = raw.replace("\r\n", "\n")
n = 0


def sub(old, new, label, expect=1):
    global txt, n
    c = txt.count(old)
    assert c == expect, "[%s] 치환 대상 %d회 (기대 %d)" % (label, c, expect)
    txt = txt.replace(old, new)
    n += 1
    print("  ok  %s" % label)


